能表达愤怒所指向的制度问题，但不依赖愤怒制造传播。
用普通人能懂的语言，同时保住法律和研究上的准确。

一句话：不煽情地呈现令人愤怒的事实，不假装中立地回避权力问题，
也不为了正义感而跨越证据。

